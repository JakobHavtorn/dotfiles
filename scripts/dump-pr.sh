#!/usr/bin/env bash
# dump-pr.sh — open a PR for dump.sh manifest changes.
#
# Called after dump.sh finishes. If manifests/ have uncommitted changes, this
# script creates a dated branch, commits, closes any stale dump PRs, and opens
# a fresh one. If nothing changed, it exits silently.
#
# Run weekly via launchd after dump.sh, or manually:
#   bash scripts/dump.sh && bash scripts/dump-pr.sh
#
# Requires: gh CLI authenticated (gh auth status). dump.sh's PATH hardening
# covers launchd sessions.
#
# Output goes to ~/Library/Logs/dotfiles-dump.log via the launchd plist
# StandardOutPath/StandardErrorPath keys. Check there if the weekly run fails.
set -euo pipefail

# launchd sessions get /usr/bin:/bin only; put Homebrew first so gh resolves
PATH="/opt/homebrew/bin:/usr/local/bin:${PATH}"
export PATH

# ── Guards ──────────────────────────────────────────────────────────────────

if ! command -v gh >/dev/null 2>&1; then
    echo "  gh not found, skipping PR creation"
    exit 0
fi

if ! gh auth status >/dev/null 2>&1; then
    echo "  gh not authenticated, skipping PR creation"
    exit 0
fi

cd "$(chezmoi source-path)"

# ── Check for changes ────────────────────────────────────────────────────────

if git diff --quiet && [ -z "$(git ls-files --others --exclude-standard)" ]; then
    echo "  no manifest changes, skipping PR creation"
    exit 0
fi

# ── Create dated branch and commit ──────────────────────────────────────────

BRANCH="chore/dump-$(date +%Y-%m-%d)"

# Clean up any leftover branch with this name (e.g. previous failed run)
git checkout main 2>/dev/null
git branch -D "$BRANCH" >/dev/null 2>&1 || true
git checkout -b "$BRANCH"

git add manifests/
git commit -m "chore: weekly dump $(date +%Y-%m-%d)

Auto-generated by scripts/dump-pr.sh from dump.sh output.
Review manifest diffs and merge or adjust as needed."

git push -u origin HEAD --force

# ── Close stale dump PRs ────────────────────────────────────────────────────

STALE_PRS=$(gh pr list --state open --search "chore: weekly dump in:title" --json number,title --jq '.[].number' 2>/dev/null || true)

for pr_num in $STALE_PRS; do
    # Don't close the PR we're about to create (shouldn't exist yet, but guard)
    gh pr close "$pr_num" --comment "Superseded by a newer weekly dump PR." 2>/dev/null || true
    # Delete the stale branch
    stale_branch=$(gh pr view "$pr_num" --json headRefName --jq '.headRefName' 2>/dev/null || true)
    if [ -n "$stale_branch" ] && [ "$stale_branch" != "$BRANCH" ]; then
        git push origin --delete "$stale_branch" 2>/dev/null || true
    fi
done

# ── Open new PR ──────────────────────────────────────────────────────────────

gh pr create \
    --title "chore: weekly dump $(date +%Y-%m-%d)" \
    --body "## Weekly manifest dump

Auto-generated by \`scripts/dump-pr.sh\`.

### Changes
$(git diff --stat main...HEAD)

### What was dumped
- Homebrew Brewfile
- pipx packages
- OMF packages and themes
- macOS defaults
- Obsidian vault config

Review the manifest diffs and merge, or push adjustments to this branch." \
    --base main

# ── Switch back to main ──────────────────────────────────────────────────────

git checkout main 2>/dev/null

echo "  PR created for $BRANCH"
